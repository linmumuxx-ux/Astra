test('长期 DM 持久化、SSE 断线恢复与后端幂等头', async ({ page, context }) => {
  const missingKeys: string[] = []
  page.on('request', req => { if (['POST','PATCH','DELETE'].includes(req.method()) && req.url().includes('/api/v1/')) { if (!req.headers()['idempotency-key']) missingKeys.push(new URL(req.url()).pathname); expect(req.url()).not.toContain(access) } })
  await login(page)
  await page.goto(`/employees/${employee.id}`)
  const content = `请记录本次真实浏览器验收 ${randomUUID()}`
  await page.getByRole('textbox', { name: '消息内容' }).fill(content)
  await page.getByRole('button', { name: '发送消息', exact: true }).click()
  await expect(page.locator('.bubble').getByText(content, { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.locator('.bubble').getByText(content, { exact: true })).toBeVisible()
  await screenshot(page, 'employee')
  await context.setOffline(true)
  await expect(page.getByText('网络离线，当前数据可能已过期。恢复网络后将重新同步。')).toBeVisible()
  await context.setOffline(false)
  await expect(page.getByText('实时同步', { exact: true })).toBeVisible({ timeout: 35000 })
  await expect(page.locator('.bubble').getByText(content, { exact: true })).toBeVisible()
  expect(missingKeys).toEqual([])
})

