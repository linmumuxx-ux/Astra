// 此套件只访问隔离新库上的真实 API，不拦截请求、不注入页面数据。
const tokenFile = process.env.ASTRA_E2E_TOKEN_FILE
test.describe.configure({ mode: 'serial' })
test.skip(!tokenFile, '需显式指定隔离新库的 ASTRA_E2E_TOKEN_FILE')
const apiUrl = process.env.ASTRA_E2E_API_URL || 'http://127.0.0.1:8202/api/v1'
const evidenceDir = resolve('../../docs/astra-1.0/evidence')
let access = '', api: APIRequestContext
let team: { id: string }, employee: { id: string }, second: { id: string }, task: { id: string }, approvalTask: { id: string }, operation: { id: string }, role: { id: string }, readonlyToken = ''
const suffix = `${Date.now()}`.slice(-7)
async function create<T>(path: string, data: unknown): Promise<T> {
  const response = await api.post(`${apiUrl}${path}`, { data, headers: { 'Idempotency-Key': randomUUID() } })
  expect(response.ok(), `真实 API 写入 ${path} 返回 ${response.status()}`).toBeTruthy()
  return response.json()
}
async function login(page: Page, value = access) {
  await page.goto('/space')
  await page.getByLabel('访问凭据', { exact: true }).fill(value)
  await page.getByRole('button', { name: '进入数字空间' }).click()
  await expect(page.locator('.brand').first()).toContainText('ASTRA')
  await expect(page.getByText('实时同步', { exact: true })).toBeVisible()
}
async function screenshot(page: Page, name: string) { await page.screenshot({ path: resolve(evidenceDir, `${name}.png`), fullPage: true, animations: 'disabled' }) }

